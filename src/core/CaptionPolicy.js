// OFF means spoken subtitles only, including during interactions and sequences.
// A speaker label or interaction/hint flag does not establish a recording.
export function isEssentialCaption(line, isVoiced = value => !!(value?.recorded || value?.voice)) {
  return !!line && (!!line.staticInspection || !!isVoiced(line));
}

