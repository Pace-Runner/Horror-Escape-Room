import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entries = {
  hallwayBasement: 'levels/hallwayBasementLevel.js',
  study: 'levels/studyLevel.js',
  bedroom: 'levels/bedroomLevel.js',
  upstairsHallway: 'levels/upstairsHallwayLevel.js',
  backrooms: 'levels/backroomsLevel.js'
};
function dependencies(entry, seen = new Set(), assets = new Set()) {
  const file = path.resolve(root, 'src', entry);
  if (seen.has(file)) return assets;
  seen.add(file);
  const source = fs.readFileSync(file, 'utf8');
  for (const match of source.matchAll(/(?:import|export)\s+(?:[\s\S]*?\s+from\s+)?['"]([^'"]+)['"]/g)) {
    const specifier = match[1];
    if (!specifier.startsWith('.')) continue;
    const target = path.resolve(path.dirname(file), specifier.split('?')[0]);
    if (target.endsWith('.js')) dependencies(path.relative(path.join(root, 'src'), target), seen, assets);
    else if (/\.(glb|png|jpe?g|webp|ttf|woff2?)$/i.test(target)) assets.add(path.relative(path.join(root, 'src'), target).replaceAll('\\', '/'));
  }
  return assets;
}
const groups = Object.fromEntries(Object.entries(entries).map(([key, entry]) => [key, [...dependencies(entry)].sort()]));
groups.common = ['assets/models/hands.glb', 'assets/models/flashlight.glb', 'assets/models/okabe.glb', 'assets/models/okabe_clean.glb'];
const assets = [...new Set(Object.values(groups).flat())].sort();
const names = new Map(assets.map((file, index) => [file, `asset${index}`]));
let output = '// Generated by scripts/generate-level-assets.mjs from static level dependencies.\n';
output += assets.map((file) => `import ${names.get(file)} from '../${file}?url';`).join('\n');
output += '\n\nexport const LEVEL_ASSETS = {\n';
for (const [key, files] of Object.entries(groups)) {
  const urls = (test) => files.filter(test).map((file) => names.get(file)).join(', ');
  output += `  ${key}: {\n    models: [${urls((file) => file.endsWith('.glb'))}],\n    textures: [${urls((file) => /\.(png|jpe?g|webp)$/.test(file))}],\n    fonts: [${urls((file) => /\.(ttf|woff2?)$/.test(file))}]\n  },\n`;
}
output += '};\n';
fs.writeFileSync(path.join(root, 'src/world/levelAssetDependencies.js'), output);
console.log(`Level dependency manifest: ${assets.length} assets, ${Object.keys(groups).length} groups.`);
